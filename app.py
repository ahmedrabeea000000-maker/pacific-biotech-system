
import streamlit as st
import pandas as pd

# إعداد الصفحة وتوسيع العرض
st.set_page_config(page_title="باسفيك بايوتك للتقاوي", layout="wide")

# 1. تعديل اسم الشركة (إزالة اسم نظام الإدارة وجعله اسم الشركة فقط)
st.title("🌱 شركة باسفيك بايوتك للتقاوي للاستيراد والتصدير")
st.markdown("---")

# القائمة الجانبية للأقسام الاحترافية
menu = [
    "📊 لوحة التقارير والأرباح الشاملة",
    "🛒 فواتير المشتريات والموردين",
    "📦 خط الغربلة وحساب الهالك والمخزن",
    "💰 فواتير المبيعات والعملاء",
    "💸 المصروفات والخزينة",
    "📅 التقفيل السنوي والتقارير المالية"
]

choice = st.sidebar.selectbox("اختر القسم", menu)

# ---------------------------------------------------------
# 1. لوحة التقارير والأرباح الشاملة (Dashboard)
# ---------------------------------------------------------
if choice == "📊 لوحة التقارير والأرباح الشاملة":
    st.header("📊 لوحة المؤشرات والتقارير المالية الاحترافية")
    
    # صف أزرار الفلترة والدورية الزمنية
    col_f1, col_f2, col_f3 = st.columns(3)
    with col_f1:
        st.selectbox("الفترة الزمنية", ["الكل", "الشهر الحالي", "الربع السنوي", "السنة المالية الحاليّة"])
    with col_f2:
        st.selectbox("فرع / مخزن", ["المخزن الرئيسي", "خط الغربلة الأول"])
    with col_f3:
        st.selectbox("نوع العملة", ["جنيه مصري (EGP)", "دولار أمريكي (USD)"])

    st.markdown("---")

    # مؤشرات أداء رئيسية عريضة وشاملة (KPIs)
    m1, m2, m3, m4, m5 = st.columns(5)
    m1.metric("إجمالي المبيعات", "145,000 جنيه", "+12% عن الشهر السابق")
    m2.metric("إجمالي المشتريات", "110,000 جنيه", "خام + جاهز")
    m3.metric("تكلفة البضاعة المباعة", "98,000 جنيه", "مباشرة")
    m4.metric("المصروفات التشغيلية", "7,500 جنيه", "تشغيل ونقل")
    m5.metric("صافي الربح الفعلي", "39,500 جنيه", "هامش ربح ممتاز 📊")

    st.markdown("---")

    # تفاصيل الأرباح والخسائر وحركة المخزون الشاملة
    col_left, col_right = st.columns(2)
    
    with col_left:
        st.subheader("📈 ملخص قائمة الدخل (أرباح وخسائر)")
        df_pl = pd.DataFrame({
            "البند المالي": ["إيرادات المبيعات الكلية", "تكلفة البضاعة المباعة", "إجمالي مجمل الربح", "المصروفات العامة والإدارية", "صافي الربح الصافي"],
            "القيمة (جنيه)": ["145,000", "98,000", "47,000", "7,500", "39,500"]
        })
        st.dataframe(df_pl, use_container_width=True)

    with col_right:
        st.subheader("📦 أرصدة المخازن الحالية (خام وتجهيز)")
        df_stock = pd.DataFrame({
            "الصنف": ["بذرة ألفصفة خام (Cuf101)", "بذرة سيريفير خام", "بذرة جاهزة للغربلة", "بذرة معبأة ومفرزة"],
            "الكمية الحالية": ["12,500 كجم", "8,000 كجم", "3,200 كجم", "5,000 كجم"],
            "الحالة": ["متوفر بالمخزن", "متوفر بالمخزن", "تحت التشغيل", "جاهز للبيع"]
        })
        st.dataframe(df_stock, use_container_width=True)

# ---------------------------------------------------------
# باقي الأقسام كمطورة للمستقبل القريب
# ---------------------------------------------------------
elif choice == "🛒 فواتير المشتريات والموردين":
    st.header("🛒 قسم فواتير المشتريات والموردين")
    st.info("جارٍ إعداد نظام فواتير المشتريات لاختيار (خام / بدون) وربطها بالمخزن تلقائياً...")

elif choice == "📦 خط الغربلة وحساب الهالك والمخزن":
    st.header("📦 خط الإنتاج والغربلة وحساب الهالك")
    st.info("هنا سيتم ربط خط الإنتاج بخصم الخام وإضافة الجاهز وحساب التكلفة الفعلية...")

elif choice == "💰 فواتير المبيعات والعملاء":
    st.header("💰 قسم فواتير المبيعات والعملاء")

elif choice == "💸 المصروفات والخزينة":
    st.header("💸 المصروفات اليومية وحركة الخزينة")

elif choice == "📅 التقفيل السنوي والتقارير المالية":
    st.header("📅 الحسابات الختامية والتقفيل السنوي للشركة")
